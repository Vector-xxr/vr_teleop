#!/usr/bin/env bash
# Shared hardware defaults matching Quest human_mimic real teleop.
# Source from record / replay launch scripts so CSV record→playback stays consistent
# (especially gripper stroke + MIT Kp/Kd). Already-set env vars are not overwritten.
#
# Usage:
#   # shellcheck disable=SC1091
#   source "${SCRIPT_DIR}/openarm_vr_compat_env.sh"

# CAN (this robot: left=can1, right=can0)
: "${OPENARM_LEFT_FOLLOWER_CAN:=can1}"
: "${OPENARM_RIGHT_FOLLOWER_CAN:=can0}"
: "${OPENARM_FOLLOWER_CAN_LEFT:=${OPENARM_LEFT_FOLLOWER_CAN}}"
: "${OPENARM_FOLLOWER_CAN_RIGHT:=${OPENARM_RIGHT_FOLLOWER_CAN}}"
: "${OPENARM_FOLLOWER_CAN:=can0}"

# Real DM4310 gripper stroke (motor rad, positive = close) — same as quest_cartesian
: "${OPENARM_GRIPPER_OPEN:=-0.98}"
: "${OPENARM_GRIPPER_CLOSED:=0.62}"
: "${OPENARM_GRIPPER_SPEED:=2.0}"
: "${OPENARM_GRIPPER_CLOSE_SPEED:=0.45}"

# MIT gains (must match Quest / follower.yaml gripper entry)
: "${OPENARM_GRIPPER_KP:=10}"
: "${OPENARM_GRIPPER_KD:=0.45}"
# Right grasp-hold uses shared Kp=10; boost hold via lag only (τ≈Kp·lag).
: "${OPENARM_GRIPPER_KP_RIGHT:=10}"
: "${OPENARM_GRIPPER_KD_RIGHT:=0.45}"

# Soft-stall + grasp-hold (Quest human_mimic). Replay dual_replay uses Control
# contact-hold with per-arm LEFT/RIGHT overrides.
: "${OPENARM_GRIPPER_SOFT_STALL:=1}"
: "${OPENARM_GRIPPER_GRASP_HOLD:=1}"
: "${OPENARM_GRIPPER_CONTACT_HOLD:=1}"
# Left: no grasp/contact hold (teleop + replay). Right: keep hold.
: "${OPENARM_GRIPPER_GRASP_HOLD_LEFT:=0}"
: "${OPENARM_GRIPPER_SOFT_STALL_LEFT:=0}"
: "${OPENARM_GRIPPER_CONTACT_HOLD_LEFT:=0}"
: "${OPENARM_GRIPPER_GRASP_HOLD_RIGHT:=1}"
: "${OPENARM_GRIPPER_SOFT_STALL_RIGHT:=1}"
: "${OPENARM_GRIPPER_CONTACT_HOLD_RIGHT:=1}"
: "${OPENARM_GRIPPER_CLOSE_DIRECTION:=1}"
: "${OPENARM_GRIPPER_GRASP_LAG:=0.18}"
: "${OPENARM_GRIPPER_GRASP_LAG_MAX:=0.22}"
# Right hold force slightly up (τ≈Kp·lag ≈ 2.4–3.0 Nm at Kp=10).
: "${OPENARM_GRIPPER_GRASP_LAG_RIGHT:=0.24}"
: "${OPENARM_GRIPPER_GRASP_LAG_MAX_RIGHT:=0.30}"
: "${OPENARM_GRIPPER_HOLD_PRELOAD:=0}"
: "${OPENARM_GRIPPER_STALL_ERROR:=0.04}"
: "${OPENARM_GRIPPER_STALL_VEL:=0.02}"
: "${OPENARM_GRIPPER_STALL_TIME:=0.12}"
: "${OPENARM_GRIPPER_HOLD_KP_SCALE:=0.55}"
: "${OPENARM_GRIPPER_STALL_WITHOUT_EFFORT:=1}"
: "${OPENARM_GRIPPER_LAG_CLAMP:=1}"

export OPENARM_LEFT_FOLLOWER_CAN OPENARM_RIGHT_FOLLOWER_CAN
export OPENARM_FOLLOWER_CAN_LEFT OPENARM_FOLLOWER_CAN_RIGHT OPENARM_FOLLOWER_CAN
export OPENARM_GRIPPER_OPEN OPENARM_GRIPPER_CLOSED
export OPENARM_GRIPPER_SPEED OPENARM_GRIPPER_CLOSE_SPEED
export OPENARM_GRIPPER_KP OPENARM_GRIPPER_KD
export OPENARM_GRIPPER_KP_RIGHT OPENARM_GRIPPER_KD_RIGHT
export OPENARM_GRIPPER_SOFT_STALL OPENARM_GRIPPER_GRASP_HOLD OPENARM_GRIPPER_CONTACT_HOLD
export OPENARM_GRIPPER_GRASP_HOLD_LEFT OPENARM_GRIPPER_SOFT_STALL_LEFT OPENARM_GRIPPER_CONTACT_HOLD_LEFT
export OPENARM_GRIPPER_GRASP_HOLD_RIGHT OPENARM_GRIPPER_SOFT_STALL_RIGHT OPENARM_GRIPPER_CONTACT_HOLD_RIGHT
export OPENARM_GRIPPER_CLOSE_DIRECTION
export OPENARM_GRIPPER_GRASP_LAG OPENARM_GRIPPER_GRASP_LAG_MAX
export OPENARM_GRIPPER_GRASP_LAG_RIGHT OPENARM_GRIPPER_GRASP_LAG_MAX_RIGHT
export OPENARM_GRIPPER_HOLD_PRELOAD
export OPENARM_GRIPPER_STALL_ERROR OPENARM_GRIPPER_STALL_VEL OPENARM_GRIPPER_STALL_TIME
export OPENARM_GRIPPER_HOLD_KP_SCALE OPENARM_GRIPPER_STALL_WITHOUT_EFFORT
export OPENARM_GRIPPER_LAG_CLAMP
